/**
 * URL Redirect for SEO (301/302 redirects)
 */
@Entity({ name: 'seo_redirects', engine: 'InnoDB' })
@Index('idx_seo_redirects_from', ['fromPath'], { unique: true })
@Index('idx_seo_redirects_store', ['storeId'])
export class SeoRedirect {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @CreateDateColumn({ name: 'created_at', type: 'datetime', precision: 6 })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'datetime', precision: 6 })
  updatedAt!: Date;

  @Column({ name: 'store_id', type: 'varchar', length: 36, nullable: true })
  storeId!: string | null; // null = global redirect

  @Column({ name: 'from_path', type: 'varchar', length: 700 })
  fromPath!: string;

  @Column({ name: 'to_path', type: 'varchar', length: 1000 })
  toPath!: string;

  @Column({ name: 'status_code', type: 'int', default: 301 })
  statusCode!: number; // 301 or 302

  @Column({ name: 'is_active', type: 'boolean', default: true })
  isActive!: boolean;
}

/**
 * Global SEO settings for the platform
 */
