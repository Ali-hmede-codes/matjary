import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Store, Product, Showcase } from './entities';
import type { Relation } from 'typeorm';

export enum RobotsDirective {
  INDEX_FOLLOW = 'index, follow',
  INDEX_NOFOLLOW = 'index, nofollow',
  NOINDEX_FOLLOW = 'noindex, follow',
  NOINDEX_NOFOLLOW = 'noindex, nofollow',
}

export enum AiRobotsDirective {
  ALLOW = 'allow',
  DISALLOW = 'disallow',
  TRAINING_ALLOW = 'training-allow',
  TRAINING_DISALLOW = 'training-disallow',
}

/**
 * SEO metadata for a store (shop)
 * Stores can customize their SEO appearance in search results
 * All fields are optional - automatic generation from store data when not set
 */
@Entity({ name: 'store_seo', engine: 'InnoDB' })
@Index('uq_store_seo_store', ['storeId'], { unique: true })
export class StoreSeo {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @CreateDateColumn({ name: 'created_at', type: 'datetime', precision: 6 })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'datetime', precision: 6 })
  updatedAt!: Date;

  @Column({ name: 'store_id', type: 'varchar', length: 36 })
  storeId!: string;

  @ManyToOne(() => Store, { onDelete: 'RESTRICT' })
  @JoinColumn({
    name: 'store_id',
    foreignKeyConstraintName: 'fk_store_seo_store',
  })
  store!: Relation<Store>;

  // Title tag (max 60 chars recommended) - AUTO-GENERATED from store.name if not set
  @Column({ name: 'meta_title', type: 'varchar', length: 120, nullable: true })
  metaTitle!: string | null;

  // Meta description (max 160 chars recommended) - AUTO-GENERATED from store.description if not set
  @Column({
    name: 'meta_description',
    type: 'varchar',
    length: 320,
    nullable: true,
  })
  metaDescription!: string | null;

  // Meta keywords (comma-separated) - AUTO-GENERATED from store categories/tags if not set
  @Column({
    name: 'meta_keywords',
    type: 'varchar',
    length: 500,
    nullable: true,
  })
  metaKeywords!: string | null;

  // Open Graph (Facebook, LinkedIn, etc.)
  @Column({ name: 'og_title', type: 'varchar', length: 120, nullable: true })
  ogTitle!: string | null;

  @Column({
    name: 'og_description',
    type: 'varchar',
    length: 320,
    nullable: true,
  })
  ogDescription!: string | null;

  @Column({
    name: 'og_image_key',
    type: 'varchar',
    length: 512,
    collation: 'utf8mb4_bin',
    nullable: true,
  })
  ogImageKey!: string | null;

  @Column({ name: 'og_type', type: 'varchar', length: 50, default: 'website' })
  ogType!: string;

  @Column({
    name: 'og_site_name',
    type: 'varchar',
    length: 100,
    nullable: true,
  })
  ogSiteName!: string | null;

  // Twitter Cards
  @Column({
    name: 'twitter_card',
    type: 'varchar',
    length: 50,
    default: 'summary_large_image',
  })
  twitterCard!: string;

  @Column({
    name: 'twitter_site',
    type: 'varchar',
    length: 100,
    nullable: true,
  })
  twitterSite!: string | null;

  @Column({
    name: 'twitter_creator',
    type: 'varchar',
    length: 100,
    nullable: true,
  })
  twitterCreator!: string | null;

  // Robots directive
  @Column({
    name: 'robots',
    type: 'enum',
    enum: RobotsDirective,
    default: RobotsDirective.INDEX_FOLLOW,
  })
  robots!: RobotsDirective;

  // AI Robots directive (GEO - Generative Engine Optimization)
  @Column({
    name: 'ai_robots',
    type: 'enum',
    enum: AiRobotsDirective,
    default: AiRobotsDirective.ALLOW,
    nullable: true,
  })
  aiRobots!: AiRobotsDirective | null;

  // AI Training permission (for LLM training crawlers)
  @Column({
    name: 'ai_training',
    type: 'enum',
    enum: AiRobotsDirective,
    default: AiRobotsDirective.TRAINING_DISALLOW,
    nullable: true,
  })
  aiTraining!: AiRobotsDirective | null;

  // Canonical URL override
  @Column({
    name: 'canonical_url',
    type: 'varchar',
    length: 1000,
    nullable: true,
  })
  canonicalUrl!: string | null;

  // JSON-LD structured data (additional custom data)
  @Column({ name: 'structured_data', type: 'json', nullable: true })
  structuredData!: Record<string, unknown> | null;

  // Hreflang alternates for multi-language
  @Column({ name: 'hreflang', type: 'json', nullable: true })
  hreflang!: Record<string, string> | null;

  // Auto-generated flag - tracks which fields were auto-generated vs manually set
  @Column({ name: 'auto_generated_fields', type: 'json', nullable: true })
  autoGeneratedFields!: string[] | null;

  // Content hash for change detection (AI attribution)
  @Column({ name: 'content_hash', type: 'varchar', length: 64, nullable: true })
  contentHash!: string | null;

  // Last time SEO was auto-regenerated
  @Column({
    name: 'last_auto_generated_at',
    type: 'datetime',
    precision: 6,
    nullable: true,
  })
  lastAutoGeneratedAt!: Date | null;
}

